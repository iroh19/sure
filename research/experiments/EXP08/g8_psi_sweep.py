"""
EXP08 -- MLOps PSI Drift-Binning Systematic Sweep & Three-Way Gate Exercise.

Read-only against /Users/batuhancitak/Desktop/sure-project/mlops/*.py -- this
script only imports drift.py/retrain.py, it never edits them. All new
artifacts (synthetic windows, JSON results, plots-as-tables) live under this
experiment_runs/EXP08/ directory.

Design decisions made here to resolve EXP08's two open_decisions:

1. Severity grid + perturbation model (open_decision #1): a MEAN-SHIFT sweep,
   delta in {0.00, 0.02, ..., 0.30} (16 points, matching drift.py's own
   mean_reference/mean_current framing directly, as the rationale doc
   recommends as "simplest and most directly comparable"). Values are
   generated by shifting each reference confidence by `-delta` (degradation
   lowers confidence) and clipping to [0, 1], which changes the *shape* of
   the distribution relative to the fixed [0,1] equal-width grid without
   just uniformly relabeling it -- this is what stresses equal-width binning
   (mass concentrating into fewer of the 10 fixed bins as the shifted
   distribution's support shrinks toward 0).
2. incumbent_map50() end-to-end check against mlflow.db (open_decision #2):
   run once, standalone, before the full sweep -- see step "0" in main().

Run with: /opt/anaconda3/bin/python3 g8_psi_sweep.py
"""
from __future__ import annotations

import json
import math
import random
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SURE_ROOT = Path("/Users/batuhancitak/Desktop/sure-project")
RUN_DIR = Path(__file__).resolve().parent

sys.path.insert(0, str(SURE_ROOT))
from mlops import drift as drift_mod  # noqa: E402
from mlops import retrain as retrain_mod  # noqa: E402


def git_provenance() -> dict:
    head = subprocess.run(["git", "-C", str(SURE_ROOT), "rev-parse", "--short", "HEAD"],
                           capture_output=True, text=True).stdout.strip()
    date = subprocess.run(["git", "-C", str(SURE_ROOT), "log", "-1", "--format=%cI"],
                           capture_output=True, text=True).stdout.strip()
    drift_log = subprocess.run(
        ["git", "-C", str(SURE_ROOT), "log", "--oneline", "--all", "--", "mlops/drift.py"],
        capture_output=True, text=True).stdout.strip().splitlines()
    return {"repo_head_short": head, "repo_head_date": date,
            "drift_py_commit_count": len(drift_log), "drift_py_commits": drift_log}


def psi_with_equal_width(reference: list[float], current: list[float]) -> tuple[float, list[dict]]:
    """Reconstruction of an equal-width-binned PSI, using drift.py's own
    histogram()/EPSILON machinery but with fixed [0,1]-spaced interior edges
    instead of bin_edges(reference). This mirrors drift.psi()'s internal loop
    exactly (same epsilon floor, same log-ratio contribution formula) so the
    only variable changed is the edge placement.

    Explicitly a FAITHFUL RECONSTRUCTION, not measured history: `git log
    --oneline --all -- mlops/drift.py` returns exactly one commit (confirmed
    below), so the historical equal-width implementation itself no longer
    exists in git history to recover.
    """
    edges = [i / drift_mod.BINS for i in range(1, drift_mod.BINS)]
    ref_h = drift_mod.histogram(reference, edges=edges)
    cur_h = drift_mod.histogram(current, edges=edges)

    total = 0.0
    per_bin = []
    for i, (r, c) in enumerate(zip(ref_h, cur_h)):
        r_adj, c_adj = max(r, drift_mod.EPSILON), max(c, drift_mod.EPSILON)
        contribution = (c_adj - r_adj) * math.log(c_adj / r_adj)
        total += contribution
        lo = "-inf" if i == 0 else f"{edges[i - 1]:.3f}"
        hi = "+inf" if i == len(edges) else f"{edges[i]:.3f}"
        per_bin.append({"bin": f"{lo}..{hi}", "reference": round(r, 4),
                         "current": round(c, 4), "contribution": round(contribution, 5)})
    return total, per_bin


def make_synthetic_degraded(reference: list[float], delta: float, rng: random.Random) -> list[float]:
    """Mean-shift degradation: subtract delta from each reference confidence,
    clip to [0,1]. Same sample count as reference so PSI compares
    like-sized windows; resampled-with-replacement so repeated deltas are
    independent draws, not the exact same shifted list every time.
    """
    sample = rng.choices(reference, k=len(reference))
    return [max(0.0, min(1.0, v - delta)) for v in sample]


def main() -> dict:
    reference = drift_mod.load_reference()
    prov = git_provenance()
    rng = random.Random(20260826)  # fixed seed for reproducibility of this sweep

    report: dict = {
        "experiment_id": "EXP08",
        "measured_at_utc": datetime.now(timezone.utc).isoformat(),
        "git_provenance": prov,
        "reference_stats": {
            "n": len(reference),
            "mean": round(sum(reference) / len(reference), 4),
            "min": round(min(reference), 4),
            "max": round(max(reference), 4),
        },
        "open_decisions_resolved": {
            "severity_grid_and_perturbation_model": (
                "Chose a mean-shift sweep, delta in [0.00, 0.30] step 0.02 (16 points), "
                "resampled with replacement from the reference at each delta then clipped "
                "to [0,1] -- matches drift.py's own mean_reference/mean_current framing "
                "and is the simplest, most directly comparable perturbation per the "
                "rationale doc's own recommendation. Variance-inflation was NOT added "
                "(out of scope for this pass); noted as a natural extension."
            ),
            "incumbent_map50_end_to_end_check": (
                "Ran retrain.decide() + retrain.incumbent_map50() once, standalone, before "
                "building the full sweep -- see 'step0_incumbent_map50_check' below."
            ),
        },
    }

    # --- Step 0: does incumbent_map50() work end-to-end against mlflow.db? ---
    try:
        val = retrain_mod.incumbent_map50()
        report["step0_incumbent_map50_check"] = {
            "ran_without_exception": True,
            "returned_value": val,
            "note": "None means either no experiment/run found with tags.metrics_valid='True', "
                    "or mlflow raised internally and was swallowed by incumbent_map50()'s own "
                    "try/except (by design, per retrain.py's own comment).",
        }
    except Exception as exc:  # should not happen -- incumbent_map50 catches internally
        report["step0_incumbent_map50_check"] = {
            "ran_without_exception": False,
            "error": f"{exc.__class__.__name__}: {exc}",
        }

    # --- Step 1-4: mean-shift severity sweep, quantile vs equal-width PSI ---
    deltas = [round(i * 0.02, 2) for i in range(0, 16)]  # 0.00 .. 0.30
    sweep = []
    for delta in deltas:
        current = make_synthetic_degraded(reference, delta, rng)
        q_psi, q_bins = drift_mod.psi(reference, current)
        ew_psi, ew_bins = psi_with_equal_width(reference, current)
        sweep.append({
            "delta": delta,
            "current_mean": round(sum(current) / len(current), 4),
            "quantile_psi": round(q_psi, 4),
            "quantile_severity": drift_mod.classify(q_psi),
            "equal_width_psi": round(ew_psi, 4),
            "equal_width_severity": drift_mod.classify(ew_psi),
        })
    report["sweep"] = sweep

    # Characterize saturation/jump behavior: find largest single-step jump in each curve
    def largest_jump(curve_key: str) -> dict:
        best = {"from_delta": None, "to_delta": None, "jump": 0.0}
        for a, b in zip(sweep, sweep[1:]):
            j = b[curve_key] - a[curve_key]
            if j > best["jump"]:
                best = {"from_delta": a["delta"], "to_delta": b["delta"], "jump": round(j, 4),
                        "from_psi": a[curve_key], "to_psi": b[curve_key]}
        return best

    report["curve_characterization"] = {
        "quantile_largest_single_step_jump": largest_jump("quantile_psi"),
        "equal_width_largest_single_step_jump": largest_jump("equal_width_psi"),
        "note": (
            "Equal-width curve is reported as a FAITHFUL RECONSTRUCTION using drift.py's "
            "own histogram()/psi()-equivalent machinery with fixed [i/10 for i in 1..9] "
            "edges, NOT as history recovered from git -- `git log --oneline --all -- "
            f"mlops/drift.py` returns exactly {prov['drift_py_commit_count']} commit(s), "
            "confirming the historical 0.06->1.05 jump narrated in drift.py's own code "
            "comment is not present as an earlier implementation in version control."
        ),
    }

    # --- Step 6: retrain.decide() on synthetic no-drift and significant-drift windows ---
    no_drift_window = make_synthetic_degraded(reference, 0.0, rng)  # delta=0 = resample only
    # pick the smallest delta in the sweep whose quantile PSI already exceeds SIGNIFICANT
    sig_candidates = [s for s in sweep if s["quantile_psi"] >= drift_mod.SIGNIFICANT]
    sig_delta = sig_candidates[0]["delta"] if sig_candidates else deltas[-1]
    significant_window = make_synthetic_degraded(reference, sig_delta, rng)

    no_drift_path = RUN_DIR / "synthetic_no_drift_window.json"
    sig_drift_path = RUN_DIR / "synthetic_significant_drift_window.json"
    no_drift_path.write_text(json.dumps({"confidences": no_drift_window}, indent=1))
    sig_drift_path.write_text(json.dumps({"confidences": significant_window}, indent=1))

    decision_no_drift = retrain_mod.decide(no_drift_window, reference=reference)
    decision_sig_drift = retrain_mod.decide(significant_window, reference=reference)

    report["retrain_gate_exercise"] = {
        "no_drift_window": {
            "n": len(no_drift_window),
            "decision": decision_no_drift.as_dict(),
        },
        "significant_drift_window": {
            "delta_used": sig_delta,
            "n": len(significant_window),
            "decision": decision_sig_drift.as_dict(),
        },
    }

    # --- Step 7: gate() at three deltas relative to MIN_IMPROVEMENT ---
    incumbent = 0.760  # arbitrary but realistic synthetic incumbent mAP50 for this exercise
    gate_cases = [
        {"label": "below_zero_delta", "candidate": incumbent - 0.010},
        {"label": "inside_noise_band", "candidate": incumbent + retrain_mod.MIN_IMPROVEMENT / 2},
        {"label": "above_min_improvement", "candidate": incumbent + retrain_mod.MIN_IMPROVEMENT * 3},
    ]
    gate_results = []
    for case in gate_cases:
        ok, reason = retrain_mod.gate(case["candidate"], incumbent)
        gate_results.append({
            "label": case["label"],
            "candidate_map50": round(case["candidate"], 4),
            "incumbent_map50": incumbent,
            "delta": round(case["candidate"] - incumbent, 4),
            "gate_passes": ok,
            "reason": reason,
        })
    report["gate_exercise"] = gate_results

    return report


if __name__ == "__main__":
    report = main()
    out_path = RUN_DIR / "exp08_output.json"
    out_path.write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
